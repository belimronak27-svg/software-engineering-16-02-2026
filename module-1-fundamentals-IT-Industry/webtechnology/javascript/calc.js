function add(){
    var a = parseInt(prompt('Enter first value:'));
    var b = parseInt(prompt('Enter second value:'));
    var c = a+b;
    alert(a+'+'+b+'='+c);
}

function multi(){
    var a = parseInt(prompt('Enter first value:'));
    var b = parseInt(prompt('Enter second value:'));
    var c = a*b;
    alert(a+'x'+b+'='+c);
}

function sub(){
    var a = parseInt(prompt('Enter first value:'));
    var b = parseInt(prompt('Enter second value:'));
    var c = a-b;
    alert(a+'-'+b+'='+c);
}

function dv(){
    var a = parseInt(prompt('Enter first value:'));
    var b = parseInt(prompt('Enter second value:'));
    var c = a/b;
    alert(a+'÷'+b+'='+c);
}